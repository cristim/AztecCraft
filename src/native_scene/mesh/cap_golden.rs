#[test]
fn zero_cap_subdivisions_equal_the_pre_cap_golden_with_and_without_round_cap() {
    for (primitive, golden_bits, golden_loops) in [
        (Primitive::Cylinder, CYLINDER_BITS, CYLINDER_LOOPS),
        (Primitive::Cone, CONE_BITS, CONE_LOOPS),
    ] {
        for round in [false, true] {
            let mesh = build(primitive, 0, round, Axis::Y);
            assert_eq!(bits(&mesh), golden_bits, "{primitive:?} points");
            let got = loops(&mesh);
            assert!(
                got.iter()
                    .map(Vec::as_slice)
                    .eq(golden_loops.iter().copied()),
                "{primitive:?} loops"
            );
        }
    }
}
